_INDEX = {}
for _group in SYNONYM_GROUPS:
    for _w in _group:
        _INDEX.setdefault(_w.lower().strip(), set()).update(_group)

def get_synonyms(word: str) -> set[str]:
    return set(_INDEX.get(word.lower().strip(), set()))
